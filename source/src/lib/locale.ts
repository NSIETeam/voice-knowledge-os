function normalizeLocale(value: string | null): AppLocale {
  return value === "en-US" ? "en-US" : DEFAULT_LOCALE;
}

export function getLocale(): AppLocale {
  if (volatileLocale) return volatileLocale;
  try {
    return normalizeLocale(window.localStorage.getItem(STORAGE_KEY));
  } catch {
    return DEFAULT_LOCALE;
  }
}

export function setLocale(locale: AppLocale): void {
  try {
    window.localStorage.setItem(STORAGE_KEY, locale);
    volatileLocale = null;
  } catch {
    // The chosen language still applies in-memory when storage is unavailable.
    volatileLocale = locale;
  }
  if (typeof document !== "undefined") document.documentElement.lang = locale;
  for (const listener of listeners) listener();
}

export function translate(source: string, locale = getLocale()): string {
  if (locale !== "zh-CN") return source;
  return zhCN[source.trim().replace(/\s+/g, " ")] ?? source;
}

export function useLocale(): AppLocale {
  return useSyncExternalStore(
    (listener) => {
      listeners.add(listener);
      return () => listeners.delete(listener);
    },
    getLocale,
    () => DEFAULT_LOCALE,
  );
}

export function formatMessage(source: string, values?: Record<string, string | number>, locale = getLocale()): string {
  return translate(source, locale).replace(/\{(\w+)\}/g, (match, key) =>
    values && Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : match,
  );
}

export function useT(): (source: string, values?: Record<string, string | number>) => string {
  const locale = useLocale();
  return (source, values) => formatMessage(source, values, locale);
}

export function applyInitialLocale(): void {
  if (typeof document !== "undefined") document.documentElement.lang = getLocale();
}
